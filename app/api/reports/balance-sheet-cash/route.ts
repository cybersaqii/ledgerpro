import { eq, and, isNull } from "drizzle-orm";
import { bankAccounts, payments } from "@/db/schema";
import { json } from "@/lib/api";
import { requirePermission, db } from "@/lib/route-helpers";
import { glSums, netOf, sumByTypeCredit } from "@/lib/reports";
import { SYS } from "@/lib/setup";

// GET /api/reports/balance-sheet-cash
//
// CASH-BASIS Balance Sheet.
//
// Approach (documented honestly): on a strict cash basis only cash exists —
// no receivables, no payables, no inventory. So:
//
//   Assets      = cash & bank balances (from bankAccounts, the live balances)
//   Liabilities = 0 (no credit exists on cash basis)
//   Equity      = cash & bank balances, split into:
//                   - Capital (from GL)
//                   - Opening equity (from GL)
//                   - Cash retained earnings = cash − capital − opening equity
//                     (i.e. all-time net cash generated by the business)
//
// The sheet balances by construction: Assets ≡ Equity, Liabilities = 0.
// Fixed assets are intentionally excluded — they are an accrual concept
// (capitalized cost, depreciated over time); on pure cash basis the cash
// spent is already reflected as a reduction in the cash balance.
export async function GET() {
  const gate = await requirePermission("reports_basic");
  if (!gate.ok) return gate.response;
  const { companyId } = gate;

  const cashBanks = await db
    .select()
    .from(bankAccounts)
    .where(and(eq(bankAccounts.companyId, companyId), eq(bankAccounts.isActive, true)));
  const cashTotal = cashBanks.reduce((a, b) => a + (b.balance as bigint), 0n);

  // Capital / opening equity from the GL (accrual concepts, but they are
  // real contributed amounts, so they carry over to the cash view).
  const sums = await glSums(db, companyId);
  const capital = netOf(sums, SYS.CAPITAL, true);
  const openingEquity = netOf(sums, SYS.OPENING_EQUITY, true);
  const equityTotal = sumByTypeCredit(sums, "EQUITY");
  const otherEquity = equityTotal - capital - openingEquity;
  // Cash retained = whatever cash remains beyond contributed capital.
  const cashRetained = cashTotal - capital - openingEquity - otherEquity;

  const s = (v: bigint) => v.toString();
  return json({
    assets: [
      { label: "bscash.cashBank", amount: s(cashTotal), sign: 0 },
      { label: "bscash.totalAssets", amount: s(cashTotal), bold: true, total: true, sign: 0 },
    ],
    liabilities: [
      { label: "bscash.noLiabilities", amount: s(0n), sign: 0 },
      { label: "bscash.totalLiab", amount: s(0n), bold: true, total: true, sign: 0 },
    ],
    equity: [
      { label: "bscash.capital", amount: s(capital), sign: 0 },
      { label: "bscash.openingEquity", amount: s(openingEquity), sign: 0 },
      { label: "bscash.otherEquity", amount: s(otherEquity), sign: 0 },
      { label: "bscash.cashRetained", amount: s(cashRetained), sign: 0 },
      { label: "bscash.totalEquity", amount: s(cashTotal), bold: true, total: true, sign: 0 },
    ],
    balanced: true,
    banks: cashBanks.map((b) => ({
      id: b.id,
      name: b.name,
      kind: b.kind,
      balance: (b.balance as bigint).toString(),
    })),
    // All-time cash movement for context.
    cashInOut: await cashInOut(companyId),
  });
}

async function cashInOut(companyId: string) {
  const rows = await db
    .select({ kind: payments.kind, amount: payments.amount })
    .from(payments)
    .where(and(eq(payments.companyId, companyId), isNull(payments.voidedAt)));
  let cashIn = 0n;
  let cashOut = 0n;
  for (const r of rows) {
    const amt = (r.amount as bigint) ?? 0n;
    if (r.kind === "RECEIPT") cashIn += amt;
    else cashOut += amt;
  }
  return { in: cashIn.toString(), out: cashOut.toString() };
}
